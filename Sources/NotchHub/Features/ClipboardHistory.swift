import AppKit
import Observation

struct ClipboardItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    var copiedAt: Date
    var isPinned = false
    /// Detected once; drives the row's preview.
    let kind: ClipboardKind

    init(text: String, copiedAt: Date, isPinned: Bool = false) {
        self.text = text
        self.copiedAt = copiedAt
        self.isPinned = isPinned
        kind = ClipboardKind.detect(text)
    }
}

enum ClipboardKind: Equatable {
    case text, code, json
    /// sRGB components 0...1.
    case color(red: Double, green: Double, blue: Double, alpha: Double)
    case link(URL)

    /// One word for the notch: what was copied.
    var name: String {
        switch self {
        case .text: String(localized: "text")
        case .code: String(localized: "code")
        case .json: "JSON"
        case .color: String(localized: "color")
        case .link: String(localized: "link")
        }
    }

    static func detect(_ text: String) -> ClipboardKind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let isSingleLine = !trimmed.contains(where: \.isNewline)
        if isSingleLine, let color = color(trimmed) { return color }
        if isSingleLine, !trimmed.contains(" "), let url = URL(string: trimmed),
           ["http", "https"].contains(url.scheme?.lowercased() ?? ""), url.host != nil {
            return .link(url)
        }
        if let first = trimmed.first, first == "{" || first == "[", trimmed.count > 2,
           (try? JSONSerialization.jsonObject(with: Data(trimmed.utf8))) != nil {
            return .json
        }
        if !isSingleLine, looksLikeCode(trimmed) { return .code }
        return .text
    }

    private static func color(_ text: String) -> ClipboardKind? {
        var hex = text.lowercased()
        guard hex.hasPrefix("#") else { return nil }
        hex.removeFirst()
        guard [3, 6, 8].contains(hex.count), hex.allSatisfy(\.isHexDigit) else { return nil }
        if hex.count == 3 { hex = hex.map { "\($0)\($0)" }.joined() }
        if hex.count == 6 { hex += "ff" }
        guard let value = UInt64(hex, radix: 16) else { return nil }
        func channel(_ shift: UInt64) -> Double { Double((value >> shift) & 0xff) / 255 }
        return .color(red: channel(24), green: channel(16), blue: channel(8), alpha: channel(0))
    }

    private static func looksLikeCode(_ text: String) -> Bool {
        let markers = ["{", "}", ";", "=>", "->", "func ", "def ", "const ", "let ", "import ", "return ", "</"]
        let hits = markers.filter { text.contains($0) }.count
        let indented = text.components(separatedBy: .newlines).contains { $0.hasPrefix("    ") || $0.hasPrefix("\t") }
        return hits >= 2 || (hits >= 1 && indented)
    }
}

/// In-memory history of copied text. Never written to disk.
@MainActor @Observable
final class ClipboardHistory {
    /// Pinned items first, then newest first.
    private(set) var items: [ClipboardItem] = []
    private(set) var accessDenied = false

    /// Called for text copied in other apps (not for our own writes).
    var onNewItem: ((ClipboardItem) -> Void)?

    /// Limit for unpinned items.
    static let limit = 20
    static let maxLength = 10_000
    /// Types set by password managers and other apps that ask not to be recorded.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.apple.is-remote-clipboard.ignored",
    ]

    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var timer: Timer?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        updateAccess()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
    }

    func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        updateAccess()
        guard !accessDenied else { return }

        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        // Files copied in Finder also carry their names as text; those belong on the shelf, not here.
        guard types.isDisjoint(with: Self.ignoredTypes),
              !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
              let text = pasteboard.string(forType: .string),
              let item = record(text)
        else { return }
        onNewItem?(item)
    }

    @discardableResult
    func record(_ text: String, now: Date = Date()) -> ClipboardItem? {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= Self.maxLength else { return nil }
        let wasPinned = items.first { $0.text == text }?.isPinned ?? false
        items.removeAll { $0.text == text }
        let item = ClipboardItem(text: text, copiedAt: now, isPinned: wasPinned)
        items.append(item)
        normalize()
        return item
    }

    /// Puts text on the pasteboard without recording it as a new copy from another app.
    func copy(_ item: ClipboardItem) {
        write(item.text)
        record(item.text)
    }

    /// Text dropped on the notch: keep it and make it pasteable.
    func add(_ text: String) {
        guard record(text) != nil else { return }
        write(text)
    }

    /// Copies pretty-printed JSON and keeps it in the history.
    func copyFormattedJSON(_ item: ClipboardItem) {
        guard let object = try? JSONSerialization.jsonObject(with: Data(item.text.utf8)),
              let data = try? JSONSerialization.data(withJSONObject: object, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]),
              let pretty = String(data: data, encoding: .utf8)
        else { return }
        add(pretty)
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        normalize()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
    }

    /// Removes everything except pinned items.
    func clear() {
        items.removeAll { !$0.isPinned }
    }

    private func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    private func normalize() {
        let pinned = items.filter(\.isPinned).sorted { $0.copiedAt > $1.copiedAt }
        let recent = items.filter { !$0.isPinned }.sorted { $0.copiedAt > $1.copiedAt }.prefix(Self.limit)
        items = pinned + recent
    }

    private func updateAccess() {
        if #available(macOS 15.4, *) {
            accessDenied = pasteboard.accessBehavior == .alwaysDeny
        }
    }
}
